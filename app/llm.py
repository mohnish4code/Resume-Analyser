"""
Groq LLM analysis layer for ATS scanner.

Responsibilities:
- Load Groq configuration
- Test Groq connection
- Analyze resume against job description
- Use deterministic ATS results as context
- Force structured JSON output
- Safely parse model responses
- Handle <think> blocks
- Provide fallback responses
"""

import json
import os
import re

from dotenv import load_dotenv
from groq import Groq


# =========================================================
# ENVIRONMENT
# =========================================================

load_dotenv(override=True)


# =========================================================
# CONFIGURATION
# =========================================================

def _get_api_key() -> str | None:
    """Get the current Groq API key."""

    load_dotenv(override=True)

    return os.getenv("GROQ_API_KEY")


def _get_model() -> str:
    """Get the configured Groq model."""

    load_dotenv(override=True)

    return os.getenv(
        "GROQ_MODEL",
        "qwen/qwen3.6-27b",
    )


# =========================================================
# SYSTEM PROMPT
# =========================================================

SYSTEM_PROMPT = """
You are an expert ATS system and technical recruiter.

Analyze a candidate's resume against a job description.

Use ONLY the information provided.

Do not invent:
- skills
- experience
- education
- projects
- achievements
- certifications
- technologies

Existing ATS scores are already calculated.
Use them as supporting information.

Return ONLY a valid JSON object.

Required structure:

{
  "summary": "Short overall assessment",
  "strengths": [
    "strength 1",
    "strength 2"
  ],
  "gaps": [
    "gap 1",
    "gap 2"
  ],
  "recommendations": [
    "recommendation 1",
    "recommendation 2"
  ]
}

Rules:
- No markdown
- No code fences
- No <think> tags
- No reasoning
- No text outside JSON
- Keep responses concise
- Use 2 to 4 items per array
"""


# =========================================================
# FALLBACK
# =========================================================

def _fallback_result() -> dict:
    """Return a standard fallback response."""

    return {
        "summary": "LLM analysis unavailable.",
        "strengths": [],
        "gaps": [],
        "recommendations": [],
    }


# =========================================================
# REMOVE THINKING BLOCKS
# =========================================================

def _remove_thinking_blocks(
    content: str,
) -> str:
    """
    Remove <think>...</think> blocks generated by
    reasoning-capable models.
    """

    if not content:
        return content

    # Complete thinking block
    content = re.sub(
        r"<think>.*?</think>",
        "",
        content,
        flags=re.IGNORECASE | re.DOTALL,
    )

    # Incomplete thinking block
    content = re.sub(
        r"<think>.*$",
        "",
        content,
        flags=re.IGNORECASE | re.DOTALL,
    )

    return content.strip()


# =========================================================
# EXTRACT JSON
# =========================================================

def _extract_json(
    content: str,
) -> str:
    """
    Extract the first complete JSON object from an
    LLM response.

    Handles:
    - <think> blocks
    - markdown code fences
    - extra text surrounding JSON
    """

    if not content:
        return ""

    # -----------------------------------------------------
    # Remove reasoning
    # -----------------------------------------------------

    content = _remove_thinking_blocks(
        content
    )

    content = content.strip()

    # -----------------------------------------------------
    # Remove markdown code fences
    # -----------------------------------------------------

    content = re.sub(
        r"```json",
        "",
        content,
        flags=re.IGNORECASE,
    )

    content = content.replace(
        "```",
        "",
    )

    content = content.strip()

    # -----------------------------------------------------
    # Find first JSON object
    # -----------------------------------------------------

    start = content.find("{")

    if start == -1:
        return ""

    # -----------------------------------------------------
    # Find matching closing brace
    # -----------------------------------------------------

    depth = 0
    in_string = False
    escaped = False

    for index in range(
        start,
        len(content),
    ):

        char = content[index]

        # Escaped character
        if escaped:
            escaped = False
            continue

        if char == "\\" and in_string:
            escaped = True
            continue

        # String boundary
        if char == '"':
            in_string = not in_string
            continue

        if in_string:
            continue

        # JSON nesting
        if char == "{":
            depth += 1

        elif char == "}":
            depth -= 1

            if depth == 0:
                return content[
                    start:index + 1
                ]

    return ""


# =========================================================
# RESPONSE PARSER
# =========================================================

def _parse_response(
    content: str,
) -> dict:
    """
    Convert Groq response into the normalized ATS
    AI-analysis structure.
    """

    if not content:
        return _fallback_result()

    json_content = _extract_json(
        content
    )

    if not json_content:

        return {
            **_fallback_result(),
            "error": (
                "LLM returned incomplete JSON."
            ),
        }

    # -----------------------------------------------------
    # Parse JSON
    # -----------------------------------------------------

    try:

        result = json.loads(
            json_content
        )

    except json.JSONDecodeError as exc:

        return {
            **_fallback_result(),
            "error": (
                "Invalid JSON returned by LLM."
            ),
            "details": str(exc),
            "raw_response": content[:4000],
        }

    # -----------------------------------------------------
    # Validate object
    # -----------------------------------------------------

    if not isinstance(
        result,
        dict,
    ):

        return {
            **_fallback_result(),
            "error": (
                "LLM returned a non-object JSON response."
            ),
        }

    # -----------------------------------------------------
    # Summary
    # -----------------------------------------------------

    summary = result.get(
        "summary",
        "No summary generated.",
    )

    if not isinstance(
        summary,
        str,
    ):
        summary = str(summary)

    # -----------------------------------------------------
    # Strengths
    # -----------------------------------------------------

    strengths = result.get(
        "strengths",
        [],
    )

    if not isinstance(
        strengths,
        list,
    ):
        strengths = [str(strengths)]

    # -----------------------------------------------------
    # Gaps
    # -----------------------------------------------------

    gaps = result.get(
        "gaps",
        [],
    )

    if not isinstance(
        gaps,
        list,
    ):
        gaps = [str(gaps)]

    # -----------------------------------------------------
    # Recommendations
    # -----------------------------------------------------

    recommendations = result.get(
        "recommendations",
        [],
    )

    if not isinstance(
        recommendations,
        list,
    ):
        recommendations = [
            str(recommendations)
        ]

    # -----------------------------------------------------
    # Normalize list values
    # -----------------------------------------------------

    strengths = [
        str(item)
        for item in strengths
    ]

    gaps = [
        str(item)
        for item in gaps
    ]

    recommendations = [
        str(item)
        for item in recommendations
    ]

    # -----------------------------------------------------
    # Final result
    # -----------------------------------------------------

    return {
        "summary": summary,
        "strengths": strengths,
        "gaps": gaps,
        "recommendations": recommendations,
    }


# =========================================================
# GROQ CONNECTION TEST
# =========================================================

def test_groq_connection() -> bool:
    """Test Groq API authentication and model access."""

    api_key = _get_api_key()

    model = _get_model()

    if not api_key:

        print(
            "Groq connection failed."
        )

        print(
            "Error: GROQ_API_KEY is not configured."
        )

        return False

    try:

        test_client = Groq(
            api_key=api_key
        )

        models = (
            test_client
            .models
            .list()
        )

        model_ids = [
            model.id
            for model in models.data
        ]

        if not model_ids:

            print(
                "Groq connection failed."
            )

            print(
                "Error: No models returned."
            )

            return False

        print(
            "Groq connection successful."
        )

        print(
            f"Available models: "
            f"{len(model_ids)}"
        )

        print(
            f"Selected model: "
            f"{model}"
        )

        if model not in model_ids:

            print(
                f"Warning: configured model "
                f"'{model}' was not returned."
            )

        return True

    except Exception as exc:

        print(
            "Groq connection failed."
        )

        print(
            f"Error: "
            f"{type(exc).__name__}"
        )

        print(
            f"Details: {exc}"
        )

        return False


# =========================================================
# MAIN LLM ANALYSIS
# =========================================================

def analyze_with_llm(
    resume_text: str,
    jd_text: str,
    ats_report: dict,
) -> dict:
    """
    Analyze resume against job description using Groq.
    """

    # -----------------------------------------------------
    # Load current configuration
    # -----------------------------------------------------

    api_key = _get_api_key()

    model = _get_model()

    if not api_key:

        return {
            **_fallback_result(),
            "error": (
                "GROQ_API_KEY not configured."
            ),
        }

    # -----------------------------------------------------
    # Create Groq client
    # -----------------------------------------------------

    try:

        client = Groq(
            api_key=api_key
        )

    except Exception as exc:

        return {
            **_fallback_result(),
            "error": type(exc).__name__,
            "details": str(exc),
        }

    # -----------------------------------------------------
    # Protect against None
    # -----------------------------------------------------

    resume_text = (
        resume_text or ""
    )[:15000]

    jd_text = (
        jd_text or ""
    )[:15000]

    # -----------------------------------------------------
    # ATS context
    # -----------------------------------------------------

    ats_context = {
        "overall_ats_score": ats_report.get(
            "overall_ats_score",
            0,
        ),

        "skills_match_score": ats_report.get(
            "skills_match_score",
            0,
        ),

        "experience_match_score": ats_report.get(
            "experience_match_score",
            0,
        ),

        "education_match_score": ats_report.get(
            "education_match_score",
            0,
        ),

        "keyword_match_score": ats_report.get(
            "keyword_match_score",
            0,
        ),

        "semantic_similarity_score": ats_report.get(
            "semantic_similarity_score",
            0,
        ),

        "matched_skills": ats_report.get(
            "matched_skills",
            [],
        ),

        "partially_matched_skills": ats_report.get(
            "partially_matched_skills",
            [],
        ),

        "missing_skills": ats_report.get(
            "missing_skills",
            [],
        ),

        "missing_keywords": ats_report.get(
            "missing_keywords",
            [],
        ),
    }

    # -----------------------------------------------------
    # SHORT USER PROMPT
    # -----------------------------------------------------

    user_prompt = f"""
Analyze this resume against this job description.

RESUME:
{resume_text}

JOB DESCRIPTION:
{jd_text}

ATS DATA:
{json.dumps(ats_context)}

Return ONLY valid JSON with exactly these fields:

{{
  "summary": "short assessment",
  "strengths": [
    "strength 1",
    "strength 2"
  ],
  "gaps": [
    "gap 1",
    "gap 2"
  ],
  "recommendations": [
    "recommendation 1",
    "recommendation 2"
  ]
}}

Use only provided information.
Do not invent skills, experience, education, projects,
achievements, or technologies.

Keep each item concise.
"""

    # -----------------------------------------------------
    # GROQ REQUEST
    # -----------------------------------------------------

    try:

        response = client.chat.completions.create(
            model=model,

            temperature=0.2,

            # Increased because Qwen previously hit
            # the completion limit before closing JSON.
            max_tokens=3000,

            response_format={
                "type": "json_object",
            },

            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                },

                {
                    "role": "user",
                    "content": user_prompt,
                },
            ],
        )

        # -------------------------------------------------
        # Extract response
        # -------------------------------------------------

        content = (
            response
            .choices[0]
            .message
            .content
        )

        if not content:

            return {
                **_fallback_result(),
                "error": (
                    "Empty response from Groq."
                ),
            }

        # -------------------------------------------------
        # Parse response
        # -------------------------------------------------

        return _parse_response(
            content
        )

    except Exception as exc:

        return {
            **_fallback_result(),
            "error": type(exc).__name__,
            "details": str(exc),
        }


